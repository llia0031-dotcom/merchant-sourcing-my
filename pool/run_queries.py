"""Runs pool/queries.sql against pool/pool.duckdb and writes the answers to pool/QUERIES.md.

    python pool/run_queries.py
"""
from __future__ import annotations

import re
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]


def blocks(sql: str) -> list[tuple[str, str]]:
    out, title, buf = [], None, []
    for line in sql.splitlines():
        m = re.match(r"--\s*(Q\d+\..*)", line)
        if m:
            if title and buf:
                out.append((title, "\n".join(buf)))
            title, buf = m.group(1).strip(), []
        elif title and not line.startswith("--"):
            buf.append(line)
    if title and buf:
        out.append((title, "\n".join(buf)))
    return [(t, q.strip().rstrip(";")) for t, q in out if q.strip()]


def md_table(cols: list[str], rows: list[tuple]) -> str:
    def cell(v):
        return "" if v is None else str(v).replace("|", "/").replace("\n", " ")
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> int:
    con = duckdb.connect(str(ROOT / "pool" / "pool.duckdb"), read_only=True)
    parts = ["# Pool queries and their answers", "",
             "Generated by `pool/run_queries.py` from `pool/queries.sql`. Scores follow the frozen rules in "
             "`pool/SCORING.md`; every candidate field comes from a quoted public page.", ""]
    for title, q in blocks((ROOT / "pool" / "queries.sql").read_text("utf-8")):
        res = con.execute(q)
        cols = [d[0] for d in res.description]
        rows = res.fetchall()
        parts += [f"## {title}", "", "```sql", q, "```", "", md_table(cols, rows), ""]
    (ROOT / "pool" / "QUERIES.md").write_text("\n".join(parts), "utf-8")
    print("wrote pool/QUERIES.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
